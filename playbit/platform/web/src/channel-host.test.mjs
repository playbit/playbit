test('the Rust boundary owns exact names, bounded handles, generations and commands',async()=>{
    const {host}=await createHost(bootstrap(encodeId(new Uint8Array(16).fill(1))));
    const boundary=new ChannelHost(()=>host.exports),utf8=new TextEncoder();
    const first=boundary.open(utf8.encode('Name'));
    assert.deepEqual(boundary.open(utf8.encode('Name')),first);
    assert.notDeepEqual(boundary.open(utf8.encode('name')),first);
    for(let i=0;i<14;i++)boundary.open(utf8.encode(String(i)));
    assert.throws(()=>boundary.open(utf8.encode('extra')),error=>error.status===-9);
    assert.throws(()=>boundary.open(Uint8Array.of(255)),error=>error.status===-3);
    const record=new DataView(first.buffer),generation=BigInt(record.getUint32(4,true)),slot=record.getUint32(0,true);
    assert.equal(boundary.name(generation,slot),'Name');
    assert.throws(()=>boundary.command('Name',2,1),error=>error.status===-3);
    assert.throws(()=>boundary.command('Name',1,32769),error=>error.status===-9);
    boundary.close(generation,slot);
    assert.throws(()=>boundary.name(generation,slot),error=>error.status===-8);
    const replacement=boundary.open(utf8.encode('Name'));
    assert.notDeepEqual(replacement,first);
    const epoch = boundary.epoch();
    assert.equal(host.exports.pb_web_guest_reset(), 0);
    assert.equal(boundary.epoch(), epoch + 1n);
    assert.equal(boundary.find('Name').length,0);
    assert.throws(()=>boundary.name(generation,new DataView(replacement.buffer).getUint32(0,true)),error=>error.status===-8);
});

test('the Rust boundary validates control identities, scoped envelopes and authentication bytes',async()=>{
    const {host}=await createHost(bootstrap(encodeId(new Uint8Array(16).fill(2))));
    const boundary=new ChannelHost(()=>host.exports),session=new Uint8Array(32).fill(7),utf8=new TextEncoder();
    const destination=boundary.destination(session,'é'.repeat(111)+'a');
    assert.equal(destination.length,255);
    assert.throws(()=>boundary.destination(session,''),AbiError);
    assert.throws(()=>boundary.destination(session,'é'.repeat(112)),AbiError);
    const source=new Uint8Array(80).fill(8),message=new Uint8Array(16).fill(9);
    const aad=boundary.aad(destination,source,message);
    const expected=Buffer.concat([Buffer.from('app.playbit.session.channel.v1'),Buffer.from([255,0]),destination,source,message]);
    assert.deepEqual(Buffer.from(aad),expected);
    const body=new Uint8Array(44);body.set(message);
    const frame={type:AP.PUBLISH,flags:0,destination,source,body};
    assert.deepEqual(boundary.receive(destination,frame),{kind:'message',aad});
    for(const bad of [{...frame,destination:boundary.destination(session,'other')},{...frame,source:source.slice(1)},{...frame,body:body.slice(1)}])assert.throws(()=>boundary.receive(destination,bad),AbiError);
    const participant={account_id:encodeId(source.slice(0,16)),device_id:encodeId(source.slice(16,32)),instance_id:encodeId(source.slice(32,48)),build_id:encodeId(source.slice(48))};
    const control={type:AP.PUBLISH,flags:0,destination:session,source:new Uint8Array(),body:utf8.encode(JSON.stringify({kind:'presence',participants:[participant]}))};
    assert.deepEqual(boundary.receive(session,control),{kind:'presence',participants:[{source,displayName:''}]});
    assert.throws(()=>boundary.receive(session,{...control,source}),AbiError);
    assert.throws(()=>boundary.receive(session,{...control,body:utf8.encode(JSON.stringify({kind:'presence',participants:[{...participant,account_id:'bad'}]}))}),AbiError);
    assert.deepEqual(boundary.receive(session,{...control,body:utf8.encode('{"kind":"update_available"}')}),{kind:'update'});
    assert.throws(()=>boundary.receive(destination,{type:AP.ERROR,flags:0,destination,source:new Uint8Array(),body:new Uint8Array(new Int32Array([-9]).buffer)}),error=>error.status===-9);
});

test('volumes, channels, files and operations share one Rust namespace with reusable slots', async () => {
    const { host } = await createHost(bootstrap(encodeId(new Uint8Array(16).fill(3))));
    const boundary = new ChannelHost(() => host.exports), utf8 = new TextEncoder();
    assert.equal(host.exports.pb_web_volumes(), 0);
    const catalog = new DataView(host.exports.memory.buffer), result = host.exports.pb_web_result();
    const volumes = catalog.getUint32(result + 16, true), revision = catalog.getBigUint64(result + 8, true);
    const volume = catalog.getBigUint64(volumes + 8, true);
    const channel = new DataView(boundary.open(utf8.encode('shared')).buffer).getBigUint64(0, true);
    assert.equal(host.exports.pb_web_volumes_acquire(revision), 0);
    const file = new DataView(host.exports.memory.buffer).getBigUint64(host.exports.pb_output(), true);
    assert.equal(host.exports.pb_web_guest_turn(1), 0);
    const operation = host.exports.pb_web_guest_begin(16, 0n);
    assert(operation > 0n);
    assert.equal(new Set([volume, channel, file, operation]).size, 4);
    assert.equal(host.exports.pb_web_guest_check(file, 16), -8);
    assert.equal(host.exports.pb_web_file_dispose(Number(operation >> 32n), Number(operation & 0xffffffffn)), -8);
    boundary.close(channel >> 32n, Number(channel & 0xffffffffn));
    const replacement = new DataView(boundary.open(utf8.encode('shared')).buffer).getBigUint64(0, true);
    assert.equal(replacement & 0xffffffffn, channel & 0xffffffffn);
    assert.equal(replacement >> 32n, (channel >> 32n) + 1n);
    assert.throws(() => boundary.name(channel >> 32n, Number(channel & 0xffffffffn)), error => error.status === -8);
    assert.equal(host.exports.pb_web_guest_complete(operation, 0), 0);
    assert.equal(host.exports.pb_web_guest_release(operation, 0, 1), 0);
    assert.equal(host.exports.pb_web_guest_turn(0), 0);
    assert.equal(host.exports.pb_web_guest_reset(), 0);
});
