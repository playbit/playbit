pub(super) fn logical(value: char, device: Key) -> Key {
    let name = match value {
        ' ' => "Space",
        '\'' => "Quote",
        ',' => "Comma",
        '-' => "Minus",
        '.' => "Period",
        '/' => "Slash",
        ';' => "Semicolon",
        '=' => "Equal",
        '[' => "LeftBracket",
        ']' => "RightBracket",
        '\\' => "Backslash",
        '`' => "Grave",
        c if c.is_ascii_alphanumeric() => {
            return Key::from_name(c.encode_utf8(&mut [0; 4])).unwrap_or(device);
        }
        _ => return device,
    };
    Key::from_name(name).unwrap_or(device)
}
