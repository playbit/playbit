let glyph code =
  let fallback = glyphs.(Char.code '?') in
  let index = glyph_index code in
  if index >= Array.length glyphs then fallback
  else
    let found = glyphs.(index) in
    if found.width = 0 then fallback else found

let layout emit text =
  let length = String.length text in
  let rec next byte width adjacent =
    if byte = length then width
    else
      let decoded = String.get_utf_8_uchar text byte in
      let following = byte + Uchar.utf_decode_length decoded in
      let code = Uchar.to_int (Uchar.utf_decode_uchar decoded) in
      if code = Char.code ' ' then next following (width + space_width) false
      else
        let glyph = glyph code in
        let left = if adjacent then width + 1 else width in
        emit left glyph;
        next following (left + glyph.width) true
  in
  next 0 0 false

let measure text = layout (fun _ _ -> ()) text

let draw set_pixel ~x ~y text =
  let emit left glyph =
    Array.iteri (fun row bits ->
      if bits <> 0 then
        for col = 0 to glyph.width - 1 do
          if bits land (1 lsl col) <> 0 then
            set_pixel (x + left + col) (y + glyph.top + row)
        done
    ) glyph.rows
  in
  ignore (layout emit text)
